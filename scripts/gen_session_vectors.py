"""Compare this library's session cookies and identities with the Python ones they
are modelled on, and generate the vectors its tests replay.

    python scripts/gen_session_vectors.py > src/mid/session_vectors_wbtest.mbt
    python scripts/gen_session_vectors.py --observe
    python scripts/gen_session_vectors.py --unsign <secret> <cookie>

The two implementations are independent: this script runs itsdangerous and
Starlette, and the file the first form writes is replayed by `moon test`. Nothing
here runs in CI — the generated vectors do.

What each form checks:

* the vectors — forward: for a payload and a timestamp, the signature this
  library must produce is taken from `itsdangerous.TimestampSigner`; backward: a
  cookie Starlette's `SessionMiddleware` wrote must read back here as the same
  session dict.
* `--unsign` — the direction neither table can hold: a cookie this library wrote
  must unsign in Python. Pass the value a session cookie carries.
* `--observe` — the same request sequences driven through Starlette's session and
  authentication middleware, printing what landed on the scope, to be read beside
  `src/mid/session_test.mbt` and `src/mid/auth_test.mbt`.
"""
import asyncio
import base64
import importlib.metadata
import json
import sys

from itsdangerous import TimestampSigner


class FixedSigner(TimestampSigner):
    """A timestamped signer that does not read the clock."""

    def __init__(self, secret, timestamp):
        super().__init__(secret)
        self.timestamp = timestamp

    def get_timestamp(self):
        return self.timestamp


def sign(secret, payload, timestamp):
    """`payload` in the timestamped form itsdangerous writes."""
    return FixedSigner(secret, timestamp).sign(payload).decode()


def starlette_cookie(secret, session, timestamp):
    """The value Starlette's SessionMiddleware stores for `session`.

    Its `send_wrapper` base64-encodes `json.dumps(scope["session"])` and signs
    that with a `TimestampSigner(str(secret_key))`.
    """
    data = base64.b64encode(json.dumps(session).encode("utf-8"))
    return sign(secret, data, timestamp)


def unsign(secret, value):
    """The payload `value` carries, or an explanation of why it does not verify."""
    try:
        return TimestampSigner(secret).unsign(value, max_age=None).decode()
    except Exception as error:  # noqa: BLE001 - reported, not handled
        return f"REFUSED: {error}"


# (secret, payload, timestamp, note) — payload is what a session cookie carries,
# a base64url text. The signatures come from itsdangerous.
SIGNATURES = [
    ("secret", "eyJ1c2VyIjoiYWRhIn0", 1700000000, "a small session at a round moment"),
    ("a longer secret with spaces", "e30", 1, "the epoch's first second"),
    ("secret", "", 1700000000, "an empty payload still has a signature"),
    (
        "secret",
        "eyJhIjoiIiwiYiI6dHJ1ZSwiYyI6bnVsbCwiZCI6W10sImUiOnt9fQ",
        4102444800,
        "every JSON shape, signed in the future",
    ),
    ("s3cr3t-\u00e9", "eyJ1c2VyIjoiYWRhIn0", 1700000000, "a secret outside ASCII"),
]

# (secret, session, timestamp) — cookies Starlette itself would write.
COOKIES = [
    ("secret", {"user": "ada"}, 1700000000),
    ("secret", {}, 1700000000),
    ("secret", {"user": "ada", "roles": ["admin", "ops"], "age": 41}, 1700000000),
    ("another secret", {"k": "v"}, 1700000000),
]


def moonbit_string(text):
    """`text` as a MoonBit string literal, escaping what the format needs."""
    out = ['"']
    for character in text:
        if character == "\\":
            out.append("\\\\")
        elif character == '"':
            out.append('\\"')
        elif character == "\n":
            out.append("\\n")
        elif 32 <= ord(character) < 127:
            out.append(character)
        else:
            out.append("\\u{%x}" % ord(character))
    out.append('"')
    return "".join(out)


def emit():
    """The vector table, as a MoonBit source file."""
    versions = (
        "itsdangerous "
        + importlib.metadata.version("itsdangerous")
        + ", Starlette "
        + importlib.metadata.version("starlette")
    )
    lines = [
        "// Generated by scripts/gen_session_vectors.py from " + versions + ".",
        "// Replayed by session_sign_wbtest.mbt; regenerate rather than edit.",
        "",
        "///|",
        "/// (secret, payload, timestamp, signed) — the value itsdangerous signs for this",
        "/// payload at this moment, which is the value this library must sign too.",
        "let signatures : Array[(String, String, Int64, String)] = [",
    ]
    for secret, payload, timestamp, note in SIGNATURES:
        lines.append(f"  // {note}")
        lines.append(
            "  ("
            + moonbit_string(secret)
            + ", "
            + moonbit_string(payload)
            + ", "
            + f"{timestamp}L"
            + ", "
            + moonbit_string(sign(secret, payload, timestamp))
            + "),"
        )
    lines += [
        "]",
        "",
        "///|",
        "/// (secret, cookie, json) — a cookie Starlette's SessionMiddleware writes for",
        "/// that session, and the JSON of the session it carries. Reading it here must",
        "/// give the same session after decoding.",
        "let cookies : Array[(String, String, String)] = [",
    ]
    for secret, session, timestamp in COOKIES:
        lines.append(
            "  ("
            + moonbit_string(secret)
            + ", "
            + moonbit_string(starlette_cookie(secret, session, timestamp))
            + ", "
            + moonbit_string(json.dumps(session))
            + "),"
        )
    lines.append("]")
    return "\n".join(lines)


# ---------- --observe: the same request sequences, through Starlette ----------


async def drive(app, scope, inbound=None):
    """One ASGI call, in-process, with a canned receive."""
    sent = []
    pending = list(
        inbound or [{"type": "http.request", "body": b"", "more_body": False}]
    )

    async def receive():
        if pending:
            return pending.pop(0)
        return {"type": "http.disconnect"}

    async def send(message):
        sent.append(message)

    await app(scope, receive, send)
    return sent


def http_scope(headers=None):
    return {
        "type": "http",
        "asgi": {"version": "3.0", "spec_version": "2.5"},
        "http_version": "1.1",
        "method": "GET",
        "scheme": "http",
        "path": "/",
        "raw_path": b"/",
        "query_string": b"",
        "root_path": "",
        "headers": [(k.encode(), v.encode()) for k, v in (headers or [])],
        "client": ("testclient", 50000),
        "server": ("testserver", 80),
    }


def set_cookie_of(sent):
    """The set-cookie value a response carried, or None."""
    for message in sent:
        if message["type"] == "http.response.start":
            for name, value in message.get("headers", []):
                if name == b"set-cookie":
                    return value.decode()
    return None


def attributes_of(set_cookie):
    """A set-cookie as its pair and a lowercased attribute map."""
    parts = [part.strip() for part in set_cookie.split(";")]
    name, _, value = parts[0].partition("=")
    attributes = {}
    for part in parts[1:]:
        key, _, attribute_value = part.partition("=")
        attributes[key.strip().lower()] = attribute_value.strip()
    return {"name": name, "value": value, "attributes": attributes}


async def observe():
    from starlette.authentication import AuthCredentials, SimpleUser
    from starlette.middleware.authentication import AuthenticationMiddleware
    from starlette.middleware.sessions import SessionMiddleware

    observations = []
    seen = []

    def recorder(inner):
        async def app(scope, receive, send):
            seen.append(
                {
                    "session": scope.get("session"),
                    "user": getattr(scope.get("user"), "display_name", None),
                    "authenticated": bool(
                        getattr(scope.get("user"), "is_authenticated", False)
                    ),
                    "auth": scope.get("auth"),
                }
            )
            await inner(scope, receive, send)

        return app

    async def answer(scope, receive, send):
        await receive()
        await send({"type": "http.response.start", "status": 200, "headers": []})
        await send({"type": "http.response.body", "body": b""})

    def login(values):
        async def app(scope, receive, send):
            scope["session"].update(values)
            await answer(scope, receive, send)

        return app

    def session_only(inner):
        return SessionMiddleware(recorder(inner), secret_key="secret")

    def sessions_and_auth(inner):
        class Bearer:
            async def authenticate(self, conn):
                # Starlette's order is (credentials, user), the reverse of the
                # tuple a reader expects from the name.
                if "ada" in conn.headers.get("authorization", ""):
                    return AuthCredentials(["authenticated"]), SimpleUser("ada")
                return None

        return SessionMiddleware(
            AuthenticationMiddleware(recorder(inner), Bearer()), secret_key="secret"
        )

    # 1. A request with no cookie: an empty session, and nothing set.
    sent = await drive(session_only(answer), http_scope())
    observations.append(
        {"sequence": "no cookie", "scope": seen[-1], "set-cookie": set_cookie_of(sent)}
    )

    # 2. A login writes the session: the response carries it, signed.
    seen.clear()
    sent = await drive(session_only(login({"user": "ada"})), http_scope())
    observations.append(
        {
            "sequence": "login writes the session",
            "scope": seen[-1],
            "set-cookie": attributes_of(set_cookie_of(sent)),
        }
    )

    # 3. A request carrying that cookie reads the session back.
    cookie = set_cookie_of(sent).split(";")[0]
    seen.clear()
    await drive(session_only(answer), http_scope([("cookie", cookie)]))
    observations.append(
        {"sequence": "the cookie comes back", "scope": seen[-1], "set-cookie": None}
    )

    # 4. An edited cookie is nobody's session.
    seen.clear()
    await drive(session_only(answer), http_scope([("cookie", "session=x" + cookie[1:])]))
    observations.append(
        {"sequence": "an edited cookie", "scope": seen[-1], "set-cookie": None}
    )

    # 5. Authentication writes `user` and `auth`, and null for nobody.
    seen.clear()
    await drive(sessions_and_auth(answer), http_scope())
    observations.append(
        {"sequence": "no credentials", "scope": seen[-1], "set-cookie": None}
    )
    seen.clear()
    await drive(
        sessions_and_auth(answer), http_scope([("authorization", "Bearer ada")])
    )
    observations.append(
        {"sequence": "a bearer token", "scope": seen[-1], "set-cookie": None}
    )

    print(json.dumps(observations, indent=2, default=str))


def main(argv):
    if len(argv) > 1 and argv[1] == "--observe":
        asyncio.run(observe())
        return 0
    if len(argv) > 1 and argv[1] == "--unsign":
        if len(argv) < 4:
            print("usage: --unsign <secret> <cookie>", file=sys.stderr)
            return 2
        print(unsign(argv[2], argv[3]))
        return 0
    print(emit())
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
